# ------------------------------------------------------------------ formatting helpers
def N(x, sig=6):
    x = float(x)
    if x == 0: return "0"
    e = int(math.floor(math.log10(abs(x))))
    if -3 <= e <= 4:
        s = f"{x:.{sig}g}"
        if "e" in s: s = f"{x:.{max(sig - e - 1, 0)}f}"
        return s
    m = x / 10**e
    if abs(round(m, sig - 1)) >= 10: m /= 10; e += 1
    return f"{m:.{sig-1}f}\\times10^{{{e}}}"

def Q(f):
    f = Fr(f)
    if f.denominator == 1: return str(f.numerator)
    if f.denominator > 20000: return N(float(f), 6)
    sg = "-" if f < 0 else ""
    return f"{sg}\\tfrac{{{abs(f.numerator)}}}{{{f.denominator}}}"

def QD(f):  # fraction plus decimal
    return f"{Q(f)}" + ("" if Fr(f).denominator == 1 else f"\;(\\approx {float(f):.5g})")

def tp(f, var=r"\frac{t}{\mathrm{ns}}"):
    f = Fr(f)
    if f == 0: return ""
    return f"\\left({var}\\right)^{{{Q(f)}}}"

def sterm(c, body):
    c = float(c)
    return (" - " if c < 0 else " + ") + N(abs(c), 5) + (("\\," + body) if body else "")

def powtxt(base, e):
    return f"{base}^{{{e}}}"

def gen_tex(p, scale=1.0, efrac=None, dfrac=None, var="y"):
    """latex of scale * F(y) for the subsonic family"""
    coef = p["sign"] * p["A"] * scale
    s = N(coef, 6) + f"\\,{var}^{{{p['p']:.5f}}}"
    if p["e"] != 0:
        s += f"\\,(1-{var})^{{{Q(efrac)}}}"
    terms = ""
    for i, a in enumerate(p["a"]):
        terms += sterm(a, var if i == 0 else f"{var}^{{{i+1}}}")
    for j, b in enumerate(p["b"]):
        ex = Q(dfrac * (j + 1))
        terms += sterm(b, f"(1-{var})^{{{ex}}}")
    terms = terms.strip()
    if terms.startswith("+ "): terms = terms[2:]
    return s + f"\\exp\\!\\Big[{terms}\\Big]"

def exp_shock(p, var):
    t = ""
    for i, a in enumerate(p["a"]):
        t += sterm(a, f"(1-{var})" if i == 0 else f"(1-{var})^{{{i+1}}}")
    t = t.strip()
    if t.startswith("+ "): t = t[2:]
    return f"\\exp\\!\\Big[{t}\\Big]"

def shock_tex(p, scale=1.0, efrac=None, var="y_s"):
    if p["fam"] == "piston":
        return N(p["F1"] * scale, 6) + f"\\,{var}^{{{Q(efrac)}}}\\," + exp_shock(p, var)
    # blend
    return N(p["F0"] * scale, 6) + sterm((p["F1"] - p["F0"]) * scale, f"{var}^{{{p['d']:.5f}}}\\," + exp_shock(p, var))

def pct(x): return f"{100*x:.3f}\\%" if x < 0.1 else f"{100*x:.1f}\\%"

